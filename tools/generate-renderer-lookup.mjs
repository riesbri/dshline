/** Derive compact Rust pages from the committed TS policy, without network/build dependencies. */
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
const sourceFile = new URL('../packages/renderer/src/width-tables.ts', import.meta.url)
const destination = new URL('../crates/dshline-renderer/src/lookup.rs', import.meta.url)
const CODE_POINTS = 0x110000
const PAGE_SIZE = 256

/**
 * Derive the exact control/ASCII/zero/wide precedence and deduplicate equal pages.
 * @param {string} source - Committed TypeScript range source.
 * @returns {{source: string, pages: number, bytes: number}} Deterministic Rust source and data footprint.
 */
export function generateLookup(source = readFileSync(sourceFile, 'utf8')) {
  const unicodeVersion = source.match(/export const WIDTH_UNICODE_VERSION = '(\d+\.\d+)'/u)?.[1]
  const documentedVersion = source.match(/Unicode Character Database (\d+\.\d+)\.\d+/u)?.[1]
  if (!unicodeVersion || unicodeVersion !== documentedVersion) throw Error('Missing or inconsistent Unicode policy version')
  function ranges(name) {
    const start = source.indexOf(`export const ${name}:`)
    const end = source.indexOf('\n]', start)
    if (start < 0 || end < 0) throw Error(`Missing policy table ${name}`)
    const result = [...source.slice(start, end).matchAll(/\[0x([\da-f]+), 0x([\da-f]+)\]/gu)].map(match => match.slice(1).map(value => parseInt(value, 16)))
    let previous = -1
    for (const [from, to] of result) {
      if (from <= previous || to < from || to >= CODE_POINTS) throw Error(`Invalid policy table ${name}`)
      previous = to
    }
    if (!result.length) throw Error(`Empty policy table ${name}`)
    return result
  }
  const widths = new Uint8Array(CODE_POINTS).fill(1)
  for (const [from, to] of ranges('WIDE_RANGES')) widths.fill(2, from, to + 1)
  for (const [from, to] of ranges('ZERO_WIDTH_RANGES')) widths.fill(0, from, to + 1)
  widths.fill(0, 0, 32)
  widths.fill(1, 32, 127)
  widths.fill(0, 127, 160)
  const indexes = [], pages = [], seen = new Map()
  for (let start = 0; start < CODE_POINTS; start += PAGE_SIZE) {
    const page = widths.slice(start, start + PAGE_SIZE), key = Buffer.from(page).toString('base64')
    if (!seen.has(key)) { seen.set(key, pages.length); pages.push(page) }
    indexes.push(seen.get(key))
  }
  // One-byte indexes save 4 KiB on today's 108 pages. A future policy that
  // exceeds this deliberately fails generation instead of truncating indexes.
  if (pages.length > 256) throw Error('Unicode policy exceeds the u8 page index; widen it explicitly')
  const lines = values => Array.from({ length: Math.ceil(values.length / 32) }, (_, i) => `    ${values.slice(i * 32, i * 32 + 32).join(', ')},`).join('\n')
  const digest = createHash('sha256').update(source).digest('hex')
  return {
    source: `// Generated by tools/generate-renderer-lookup.mjs; do not edit.\n// Project Unicode policy sha256: ${digest}\n// Unicode data copyright Unicode, Inc.; https://www.unicode.org/license.txt\npub const UNICODE_VERSION: &str = "${unicodeVersion}";\npub static INDEX: [u8; ${indexes.length}] = [\n${lines(indexes)}\n];\npub static PAGES: [[u8; ${PAGE_SIZE}]; ${pages.length}] = [\n${pages.map(page => `    [${[...page].join(', ')}],`).join('\n')}\n];\n`,
    pages: pages.length, bytes: indexes.length + pages.length * PAGE_SIZE,
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.length > 3 || process.argv[2] && process.argv[2] !== '--check') throw Error('usage: node tools/generate-renderer-lookup.mjs [--check]')
  const generated = generateLookup()
  if (process.argv[2] === '--check') {
    if (readFileSync(destination, 'utf8') !== generated.source) throw Error('Rust lookup is stale; run node tools/generate-renderer-lookup.mjs')
  } else writeFileSync(destination, generated.source)
  console.log(`Rust width lookup: ${generated.pages} unique pages, ${generated.bytes} data bytes`)
}
